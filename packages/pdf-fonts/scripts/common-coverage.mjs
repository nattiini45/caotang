/* global URL, console */
// The root lint config gives Node globals to tools/ and to TypeScript only. This script runs under Node, so it names the
// globals it reads here rather than widening the config for one file.
/**
 * Writes src/coverage/noto-common-coverage.ts, the code points the two common fonts map (their cmaps), from the font files
 * themselves (vendor/noto-sans-cjk and vendor/noto-emoji, WOFF files fontkit reads as they are).
 *
 *   node packages/pdf-fonts/scripts/common-coverage.mjs
 *
 * A document whose characters are all in a table reads the common font and not the full one (coverage.ts `cjkCommonCovers`,
 * `emojiCommonCovers`). test/common-fonts.test.ts reads the fonts again and checks the tables against them, and checks that the
 * common font draws each of its characters as the full one does.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import fontkit from '@pdf-lib/fontkit';

/** The "gap.length" base-36 encoding of the code points of a font (scripts/cjk-coverage.mjs). */
function rangesOf(file) {
  const font = fontkit.create(readFileSync(new URL(file, import.meta.url)));
  const points = [...font.characterSet].sort((a, b) => a - b);
  const tokens = [];
  let previousEnd = -1;
  for (let i = 0; i < points.length; ) {
    let j = i;
    while (j + 1 < points.length && points[j + 1] === points[j] + 1) j++;
    tokens.push(`${(points[i] - previousEnd - 1).toString(36)}.${(j - i + 1).toString(36)}`);
    previousEnd = points[j];
    i = j + 1;
  }
  return { tokens, count: points.length };
}

/** A string constant wrapped to the width the other coverage files use. */
function constant(name, tokens) {
  const lines = tokens.join(' ').match(/.{1,116}(?: |$)/g).map((line) => `  '${line.trimEnd()} ' +`);
  lines[lines.length - 1] = lines[lines.length - 1].replace(/ ' \+$/, "';");
  return `export const ${name} =\n${lines.join('\n')}`;
}

const cjk = rangesOf('../../../vendor/noto-sans-cjk/NotoSansMonoCJKsc-Regular-common.woff');
const emoji = rangesOf('../../../vendor/noto-emoji/NotoEmoji-Regular-common.woff');
writeFileSync(
  new URL('../src/coverage/noto-common-coverage.ts', import.meta.url),
  `/**
 * The code points the two common fonts map (their cmaps): Noto Sans Mono CJK SC cut to the characters of everyday use
 * (vendor/noto-sans-cjk, common-charset.txt) and Noto Emoji cut to the single-code-point emoji and the keycaps (vendor/noto-emoji,
 * common-emoji.txt). A document whose characters are all in them reads these files and not the full fonts. Generated by
 * scripts/common-coverage.mjs from the font files; do not edit.
 *
 * Each range is "gap.length" in base 36: the gap after the previous range's last code point, and the range's length.
 */
${constant('NOTO_CJK_COMMON_RANGES', cjk.tokens)}

/** How many code points the common CJK font maps. The test checks the table against the font with it. */
export const NOTO_CJK_COMMON_CODE_POINTS = ${cjk.count};

${constant('NOTO_EMOJI_COMMON_RANGES', emoji.tokens)}

/** How many code points the common emoji font maps. The test checks the table against the font with it. */
export const NOTO_EMOJI_COMMON_CODE_POINTS = ${emoji.count};
`,
);
console.log(`${cjk.count} CJK code points in ${cjk.tokens.length} ranges, ${emoji.count} emoji code points in ${emoji.tokens.length} ranges`);
