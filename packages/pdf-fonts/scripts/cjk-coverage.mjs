/* global URL, console */
// The root lint config gives Node globals to tools/ and to TypeScript only. This script runs under Node, so it names the
// globals it reads here rather than widening the config for one file.
/**
 * Writes src/coverage/noto-cjk-coverage.ts, the code points the CJK fallback font maps, from the font file itself
 * (vendor/noto-sans-cjk, a WOFF fontkit reads as it is).
 *
 *   node packages/pdf-fonts/scripts/cjk-coverage.mjs
 *
 * test/coverage.test.ts reads the font's cmap again and checks the table against it, so a font update without a rerun fails.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import fontkit from '@pdf-lib/fontkit';

const font = fontkit.create(readFileSync(new URL('../../../vendor/noto-sans-cjk/NotoSansMonoCJKsc-Regular.woff', import.meta.url)));
const points = [...font.characterSet].sort((a, b) => a - b);
const tokens = [];
let previousEnd = -1;
for (let i = 0; i < points.length; ) {
  let j = i;
  while (j + 1 < points.length && points[j + 1] === points[j] + 1) j++;
  // Each range is "gap.length" in base 36: the gap from the end of the range before it, and its own length.
  tokens.push(`${(points[i] - previousEnd - 1).toString(36)}.${(j - i + 1).toString(36)}`);
  previousEnd = points[j];
  i = j + 1;
}
const body = tokens.join(' ');
const lines = body.match(/.{1,116}(?: |$)/g).map((line) => `  '${line.trimEnd()} ' +`);
lines[lines.length - 1] = lines[lines.length - 1].replace(/ ' \+$/, "';");
writeFileSync(
  new URL('../src/coverage/noto-cjk-coverage.ts', import.meta.url),
  `/**
 * The code points Noto Sans Mono CJK SC maps (its cmap), so the layout knows before the font loads which characters the
 * fallback prints and which print as "?". Generated by scripts/cjk-coverage.mjs from the font file; do not edit.
 *
 * Each range is "gap.length" in base 36: the gap after the previous range's last code point, and the range's length.
 */
export const NOTO_CJK_RANGES =
${lines.join('\n')}

/** How many code points the font maps. The test checks the table against the font with it. */
export const NOTO_CJK_CODE_POINTS = ${points.length};
`,
);
console.log(`${points.length} code points in ${tokens.length} ranges`);
