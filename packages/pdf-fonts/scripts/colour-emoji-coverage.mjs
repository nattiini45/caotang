/* global URL, console */
// The root lint config gives Node globals to tools/ and to TypeScript only. This script runs under Node, so it names the
// globals it reads here rather than widening the config for one file.
/**
 * Writes src/coverage/noto-colour-emoji-coverage.ts, what the colour emoji asset has, from the asset itself
 * (vendor/noto-color-emoji/NotoColorEmoji.bin):
 *
 *   node packages/pdf-fonts/scripts/colour-emoji-coverage.mjs
 *
 * Three constants: the file's length and SHA-256, which `ColourEmoji.open` checks every byte it is given against, and the keys the
 * asset has, as the code points of each key in base 36 joined by dots, space-separated (the emoji table's encoding): the layout
 * reads them before the asset loads, to know which emoji print in colour and which keep the monochrome font.
 *
 * test/colour-emoji.test.ts reads the asset again and checks the table against it, so an asset rebuilt without a rerun fails.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { inflateSync } from 'node:zlib';

const file = readFileSync(new URL('../../../vendor/noto-color-emoji/NotoColorEmoji.bin', import.meta.url));
const view = new DataView(file.buffer, file.byteOffset, file.byteLength);
const packedIndex = view.getUint32(8);
const index = JSON.parse(inflateSync(file.subarray(16, 16 + packedIndex)).toString('utf8'));

const keys = index.keys.split('\n').map((key) => key.split('-').map((hex) => parseInt(hex, 16).toString(36)).join('.'));
const sha = createHash('sha256').update(file).digest('hex');

const lines = [];
let line = '';
for (const key of keys) {
  if (line.length + key.length + 1 > 118) {
    lines.push(line);
    line = '';
  }
  line += (line === '' ? '' : ' ') + key;
}
lines.push(line);

const text = `/**
 * What the colour emoji asset has, so the layout knows before the asset loads which emoji print in colour. Generated by
 * scripts/colour-emoji-coverage.mjs from vendor/noto-color-emoji/NotoColorEmoji.bin; do not edit.
 */

/** The asset's length in bytes. */
export const NOTO_COLOUR_EMOJI_BYTES = ${file.byteLength};

/** The asset's SHA-256. */
export const NOTO_COLOUR_EMOJI_SHA256 = '${sha}';

/**
 * The emoji the asset has, by key: the code points without variation selectors, each in base 36, joined by dots, space-separated
 * (${keys.length} of them; colour-emoji.ts \`colourEmojiKey\`).
 */
export const NOTO_COLOUR_EMOJI_KEYS =
${lines.map((entry, i) => `  '${entry}${i === lines.length - 1 ? "';" : " ' +"}`).join('\n')}
`;
writeFileSync(new URL('../src/coverage/noto-colour-emoji-coverage.ts', import.meta.url), text);
console.log(`${keys.length} keys, ${file.byteLength} bytes, ${sha}`);
