/* global URL, console */
// The root lint config gives Node globals to tools/ and to TypeScript only. This script runs under Node, so it names the
// globals it reads here rather than widening the config for one file.
/**
 * Writes src/coverage/noto-arabic-coverage.ts, noto-hebrew-coverage.ts and noto-devanagari-coverage.ts, the code points the
 * Arabic, Hebrew and Devanagari fonts map, from the font files themselves (vendor/noto-sans-arabic, vendor/noto-sans-hebrew,
 * vendor/noto-sans-devanagari).
 *
 *   node packages/pdf-fonts/scripts/script-font-coverage.mjs
 *
 * test/coverage.test.ts reads each font's cmap again and checks the table against it, so a font update without a rerun fails.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import fontkit from '@pdf-lib/fontkit';

const FONTS = [
  { vendor: 'noto-sans-arabic', file: 'NotoSansArabic-Regular.ttf', name: 'Noto Sans Arabic', constant: 'NOTO_ARABIC', output: 'noto-arabic-coverage.ts' },
  { vendor: 'noto-sans-hebrew', file: 'NotoSansHebrew-Regular.ttf', name: 'Noto Sans Hebrew', constant: 'NOTO_HEBREW', output: 'noto-hebrew-coverage.ts' },
  { vendor: 'noto-sans-devanagari', file: 'NotoSansDevanagari-Regular.ttf', name: 'Noto Sans Devanagari', constant: 'NOTO_DEVANAGARI', output: 'noto-devanagari-coverage.ts' },
];

for (const { vendor, file, name, constant, output } of FONTS) {
  const font = fontkit.create(readFileSync(new URL(`../../../vendor/${vendor}/${file}`, import.meta.url)));
  const points = [...font.characterSet].sort((a, b) => a - b);
  const tokens = [];
  let previousEnd = -1;
  for (let i = 0; i < points.length; ) {
    let j = i;
    while (j + 1 < points.length && points[j + 1] === points[j] + 1) j++;
    // Each range is "gap.length" in base 36: the gap from the end of the range before it, and its own length.
    tokens.push(`${(points[i] - previousEnd - 1).toString(36)}.${(j - i + 1).toString(36)}`);
    previousEnd = points[j];
    i = j + 1;
  }
  const lines = tokens
    .join(' ')
    .match(/.{1,116}(?: |$)/g)
    .map((line) => `  '${line.trimEnd()} ' +`);
  lines[lines.length - 1] = lines[lines.length - 1].replace(/ ' \+$/, "';");
  writeFileSync(
    new URL(`../src/coverage/${output}`, import.meta.url),
    `/**
 * The code points ${name} maps (its cmap), so the layout knows before the font loads which characters it prints and which print
 * as "?". Generated by scripts/script-font-coverage.mjs from the font file; do not edit.
 *
 * Each range is "gap.length" in base 36: the gap after the previous range's last code point, and the range's length.
 */
export const ${constant}_RANGES =
${lines.join('\n')}

/** How many code points the font maps. The test checks the table against the font with it. */
export const ${constant}_CODE_POINTS = ${points.length};
`,
  );
  console.log(`${name}: ${points.length} code points in ${tokens.length} ranges`);
}
