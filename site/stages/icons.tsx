export type GlyphName = keyof typeof APP | keyof typeof LUCIDE

/** One glyph at the scene's icon size (16 by default), stroked in the current colour. Decorative. */
export function Glyph({ name, size = 16, className }: { name: GlyphName; size?: number; className?: string }): ReactNode {
  const paths = (APP as Record<string, ReactNode>)[name] ?? (LUCIDE as Record<string, ReactNode>)[name]
  return (
    <svg className={`cao-glyph${className ? ` ${className}` : ''}`} viewBox="0 0 24 24" width={size} height={size} aria-hidden="true" focusable="false">
      {paths}
    </svg>
  )
}
